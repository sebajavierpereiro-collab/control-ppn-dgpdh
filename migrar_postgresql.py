"""Ola 5 · Reforma 98: pase de SQLite a PostgreSQL, PREPARADO (la app sigue funcionando con SQLite).

Decisión: dejarlo listo y probado para cuando el uso simultáneo lo pida. Este script copia TODA la base a PostgreSQL
sin tocar la base SQLite:

    python migrar_postgresql.py --sql dgpdh_postgres.sql
        Genera un archivo .sql (tablas, índices y datos) que Sistemas carga con:
        psql -U dgpdh -d dgpdh -f dgpdh_postgres.sql

    python migrar_postgresql.py --url postgresql://dgpdh:CLAVE@localhost:5432/dgpdh
        Copia directo (requiere: python -m pip install "psycopg[binary]") y al final compara la cantidad de filas
        de cada tabla en las dos bases.

    python migrar_postgresql.py --informe
        Solo muestra tablas, filas y lo que habría que adaptar.

Qué NO hace todavía (por eso la app sigue en SQLite): el código usa sqlite3 directamente en database.py y otros
módulos; para funcionar sobre PostgreSQL hay que cambiar la conexión y unas pocas consultas propias de SQLite
(búsqueda de texto FTS5, «INSERT ... ON CONFLICT» ya es compatible, COLLATE NOCASE, funciones substr/strftime).
La lista está en el README («Pase a PostgreSQL»). Cuándo conviene: ver Administración → Base de datos.
"""
import argparse
import sqlite3
import sys
from pathlib import Path

LOTE = 500
OMITIR = ("sqlite_", "notas_fts")  # tablas internas de SQLite y el índice de texto (en PostgreSQL se rehace con tsvector)


def _ruta_db_por_defecto():
    try:
        import database
        return Path(database.RUTA_DB)
    except Exception:
        return Path(__file__).resolve().parent / "datos" / "dgpdh.db"


def tablas(con):
    return [f[0] for f in con.execute("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")
            if not f[0].startswith(OMITIR)]


def _tipo_pg(tipo_sqlite):
    t = (tipo_sqlite or "").upper()
    if "INT" in t:
        return "BIGINT"
    if any(x in t for x in ("REAL", "FLOA", "DOUB", "NUMERIC")):
        return "DOUBLE PRECISION"
    if "BLOB" in t:
        return "BYTEA"
    return "TEXT"


def _q(nombre):
    return '"' + nombre.replace('"', '""') + '"'


def _default_pg(valor, tipo):
    if valor is None:
        return None
    v = str(valor).strip()
    if v.upper() in ("CURRENT_TIMESTAMP", "(CURRENT_TIMESTAMP)"):
        return "CURRENT_TIMESTAMP"
    if v.startswith("(") and v.endswith(")"):
        v = v[1:-1].strip()
    return v


def ddl_tabla(con, tabla):
    cols = con.execute(f"PRAGMA table_info({_q(tabla)})").fetchall()
    pk = [c for c in cols if c[5]]
    autoinc = len(pk) == 1 and "INT" in (pk[0][2] or "").upper()
    defs = []
    for cid, nombre, tipo, notnull, dflt, es_pk in cols:
        if autoinc and es_pk:
            defs.append(f"{_q(nombre)} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
            continue
        d = f"{_q(nombre)} {_tipo_pg(tipo)}"
        if notnull:
            d += " NOT NULL"
        dv = _default_pg(dflt, tipo)
        if dv is not None:
            d += f" DEFAULT {dv}"
        defs.append(d)
    if pk and not autoinc:
        defs.append("PRIMARY KEY (" + ", ".join(_q(c[1]) for c in sorted(pk, key=lambda c: c[5])) + ")")
    sentencias = [f"CREATE TABLE IF NOT EXISTS {_q(tabla)} (\n    " + ",\n    ".join(defs) + "\n);"]
    for idx in con.execute(f"PRAGMA index_list({_q(tabla)})").fetchall():
        nombre, unico, origen = idx[1], idx[2], idx[3] if len(idx) > 3 else "c"
        if origen == "pk":
            continue
        columnas = [c[2] for c in con.execute(f"PRAGMA index_info({_q(nombre)})").fetchall()]
        if not columnas or any(c is None for c in columnas):
            continue  # índices sobre expresiones: se rehacen a mano si hacen falta
        nombre_pg = nombre if not nombre.startswith("sqlite_autoindex") else f"ux_{tabla}_{'_'.join(columnas)}"
        sentencias.append(f"CREATE {'UNIQUE ' if unico else ''}INDEX IF NOT EXISTS {_q(nombre_pg)} ON {_q(tabla)} ("
                          + ", ".join(_q(c) for c in columnas) + ");")
    return sentencias, (pk[0][1] if autoinc else None)


def _literal(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, bytes):
        return "'\\x" + v.hex() + "'::bytea"
    return "'" + str(v).replace("'", "''").replace("\x00", "") + "'"


def escribir_sql(ruta_db, salida):
    con = sqlite3.connect(ruta_db)
    total = 0
    with open(salida, "w", encoding="utf-8") as f:
        f.write("-- Base DGPDH copiada desde SQLite para PostgreSQL (generado por migrar_postgresql.py)\n")
        f.write("BEGIN;\nSET client_encoding = 'UTF8';\n\n")
        identidades = []
        for t in tablas(con):
            sentencias, col_id = ddl_tabla(con, t)
            f.write("\n".join(sentencias) + "\n")
            cols = [c[1] for c in con.execute(f"PRAGMA table_info({_q(t)})").fetchall()]
            lista = ", ".join(_q(c) for c in cols)
            filas = con.execute(f"SELECT {lista} FROM {_q(t)}")
            while True:
                lote = filas.fetchmany(LOTE)
                if not lote:
                    break
                f.write(f"INSERT INTO {_q(t)} ({lista}) OVERRIDING SYSTEM VALUE VALUES\n" if col_id else f"INSERT INTO {_q(t)} ({lista}) VALUES\n")
                f.write(",\n".join("(" + ", ".join(_literal(v) for v in r) + ")" for r in lote) + ";\n")
                total += len(lote)
            if col_id:
                identidades.append((t, col_id))
            f.write("\n")
        for t, c in identidades:  # que los próximos id sigan después del último copiado
            f.write(f"SELECT setval(pg_get_serial_sequence('{_q(t)}', '{c}'), COALESCE((SELECT MAX({_q(c)}) FROM {_q(t)}), 0) + 1, false);\n")
        f.write("COMMIT;\n")
    con.close()
    return total


def copiar_directo(ruta_db, url):
    try:
        import psycopg
    except ImportError:
        print('Falta el conector de PostgreSQL. Instalalo con:  python -m pip install "psycopg[binary]"')
        return 2
    src = sqlite3.connect(ruta_db)
    with psycopg.connect(url) as pg:
        with pg.cursor() as cur:
            for t in tablas(src):
                sentencias, col_id = ddl_tabla(src, t)
                for s in sentencias:
                    cur.execute(s)
                cols = [c[1] for c in src.execute(f"PRAGMA table_info({_q(t)})").fetchall()]
                lista = ", ".join(_q(c) for c in cols)
                with cur.copy(f"COPY {_q(t)} ({lista}) FROM STDIN") as copia:
                    for r in src.execute(f"SELECT {lista} FROM {_q(t)}"):
                        copia.write_row(r)
                if col_id:
                    cur.execute(f"SELECT setval(pg_get_serial_sequence(%s, %s), COALESCE((SELECT MAX({_q(col_id)}) FROM {_q(t)}), 0) + 1, false)",
                                (_q(t), col_id))
            pg.commit()
            distintas = []
            for t in tablas(src):
                a = src.execute(f"SELECT COUNT(*) FROM {_q(t)}").fetchone()[0]
                cur.execute(f"SELECT COUNT(*) FROM {_q(t)}")
                b = cur.fetchone()[0]
                print(f"{t:32} SQLite {a:>8}  PostgreSQL {b:>8}  {'OK' if a == b else 'DIFERENTE'}")
                if a != b:
                    distintas.append(t)
    src.close()
    print("Copia completa y verificada." if not distintas else f"Revisar: {', '.join(distintas)}")
    return 0 if not distintas else 1


def informe(ruta_db):
    con = sqlite3.connect(ruta_db)
    filas = [(t, con.execute(f"SELECT COUNT(*) FROM {_q(t)}").fetchone()[0]) for t in tablas(con)]
    con.close()
    return filas


def main(argv=None):
    p = argparse.ArgumentParser(description="Copia la base de la app DGPDH de SQLite a PostgreSQL")
    p.add_argument("--db", help="Ruta de la base SQLite (por defecto, la de la app)")
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--sql", help="Archivo .sql a generar")
    g.add_argument("--url", help="postgresql://usuario:clave@servidor:5432/base")
    g.add_argument("--informe", action="store_true")
    a = p.parse_args(argv)
    ruta = Path(a.db) if a.db else _ruta_db_por_defecto()
    if not ruta.is_file():
        print(f"No encuentro la base: {ruta}")
        return 2
    if a.informe:
        for t, n in informe(ruta):
            print(f"{t:32} {n:>8} filas")
        return 0
    if a.sql:
        n = escribir_sql(ruta, a.sql)
        print(f"Listo: {a.sql} ({n} filas). Cargalo con:  psql -U USUARIO -d BASE -f {a.sql}")
        return 0
    return copiar_directo(ruta, a.url)


if __name__ == "__main__":
    sys.exit(main())
